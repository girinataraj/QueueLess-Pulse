import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { ErrorBoundary, ToastProvider } from './components/feedback';
import { App } from './app';
import './styles.css';
const client = new QueryClient({ defaultOptions: { queries: { refetchOnWindowFocus: true, retry: 1 }, mutations: { retry: false } } });
createRoot(document.getElementById('root')!).render(<StrictMode><ErrorBoundary><QueryClientProvider client={client}><BrowserRouter basename="/app"><ToastProvider><App/></ToastProvider></BrowserRouter></QueryClientProvider></ErrorBoundary></StrictMode>);
if ('serviceWorker' in navigator) window.addEventListener('load', () => { void navigator.serviceWorker.register('/sw.js').catch(() => {}); });
