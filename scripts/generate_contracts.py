"""Generate strict TS response types from the JSON Schema used by API tests."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts(value) for value in schema['anyOf'])
    kind = schema['type']
    if kind == 'object':
        required = schema.get('required', [])
        return '{ ' + '; '.join(name + ('' if name in required else '?') + ': ' + ts(value) for name, value in schema['properties'].items()) + ' }'
    if kind == 'array':
        return 'Array<' + ts(schema['items']) + '>'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}[kind]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads((ROOT / 'contracts/api.schema.json').read_text(encoding='utf-8'))
    output = '// Generated by scripts/generate_contracts.py. Do not edit.\n' + '\n'.join('export type ' + name + ' = ' + ts(value) + ';' for name, value in schema['$defs'].items()) + '\n'
    path = ROOT / 'frontend/src/api/contracts.ts'
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != output:
            raise SystemExit('API contracts differ; run python scripts/generate_contracts.py')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output, encoding='utf-8')

if __name__ == '__main__':
    main()
